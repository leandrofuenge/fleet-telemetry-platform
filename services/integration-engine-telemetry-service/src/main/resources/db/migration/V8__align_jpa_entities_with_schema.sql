-- O tenant de viagens legadas é inferido somente a partir de relacionamentos
-- que já pertencem a um tenant. A migration falha em vez de atribuir dados ao
-- tenant errado quando não existe informação suficiente.
ALTER TABLE viagens ADD COLUMN IF NOT EXISTS tenant_id BIGINT;

UPDATE viagens viagem
SET tenant_id = COALESCE(
    (SELECT veiculo.tenant_id FROM veiculos veiculo WHERE veiculo.id = viagem.veiculo_id),
    (SELECT motorista.tenant_id FROM motoristas motorista WHERE motorista.id = viagem.motorista_id)
)
WHERE viagem.tenant_id IS NULL;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM viagens WHERE tenant_id IS NULL) THEN
        RAISE EXCEPTION
            'Não foi possível determinar o tenant de todas as viagens legadas';
    END IF;
END $$;

ALTER TABLE viagens ALTER COLUMN tenant_id SET NOT NULL;
