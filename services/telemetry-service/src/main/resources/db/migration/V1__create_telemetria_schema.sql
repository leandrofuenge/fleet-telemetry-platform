-- VIEW DE VEÍCULOS COM DOCUMENTOS VENCIDOS (RN-VEI-003)
-- =============================================================================

CREATE OR REPLACE VIEW vw_veiculos_documentos_vencidos AS
SELECT
    v.id,
    v.tenant_id,
    v.placa,
    v.modelo,
    v.marca,
    v.pbt_kg,
    v.tacografo_obrigatorio,
    v.data_venc_tacografo,
    v.data_venc_crlv,
    v.data_venc_seguro,
    v.data_venc_dpvat,
    v.data_venc_rcf,
    v.data_venc_vistoria,
    v.data_venc_rntrc,
    c.nome_razao_social AS tenant_nome,
    CASE
        WHEN v.data_venc_crlv < CURRENT_DATE THEN 'CRLV'
        WHEN v.data_venc_seguro < CURRENT_DATE THEN 'Seguro'
        WHEN v.data_venc_dpvat < CURRENT_DATE THEN 'DPVAT'
        WHEN v.data_venc_rcf < CURRENT_DATE THEN 'RCF'
        WHEN v.data_venc_vistoria < CURRENT_DATE THEN 'Vistoria'
        WHEN v.data_venc_rntrc < CURRENT_DATE THEN 'RNTRC'
        WHEN v.tacografo_obrigatorio = TRUE AND v.data_venc_tacografo < CURRENT_DATE THEN 'Tacógrafo'
        ELSE NULL
    END AS documento_vencido,
    LEAST(
        COALESCE(v.data_venc_crlv, (CURRENT_DATE + 999)),
        COALESCE(v.data_venc_seguro, (CURRENT_DATE + 999)),
        COALESCE(v.data_venc_dpvat, (CURRENT_DATE + 999)),
        COALESCE(v.data_venc_rcf, (CURRENT_DATE + 999)),
        COALESCE(v.data_venc_vistoria, (CURRENT_DATE + 999)),
        COALESCE(v.data_venc_rntrc, (CURRENT_DATE + 999)),
        COALESCE(v.data_venc_tacografo, (CURRENT_DATE + 999))
    ) AS proximo_vencimento
FROM veiculos v
INNER JOIN clientes c ON v.tenant_id = c.id
WHERE v.ativo = TRUE
  AND (
      v.data_venc_crlv < CURRENT_DATE OR
      v.data_venc_seguro < CURRENT_DATE OR
      v.data_venc_dpvat < CURRENT_DATE OR
      v.data_venc_rcf < CURRENT_DATE OR
      v.data_venc_vistoria < CURRENT_DATE OR
      v.data_venc_rntrc < CURRENT_DATE OR
      (v.tacografo_obrigatorio = TRUE AND v.data_venc_tacografo < CURRENT_DATE)
  );

-- =============================================================================
-- VIEW DE VEÍCULOS COM TACÓGRAFO VENCENDO EM 30/7 DIAS (RN-VEI-002)
-- =============================================================================

CREATE OR REPLACE VIEW vw_tacografo_proximo_vencimento AS
SELECT
    v.id,
    v.tenant_id,
    v.placa,
    v.modelo,
    v.pbt_kg,
    v.data_venc_tacografo,
    (v.data_venc_tacografo - CURRENT_DATE) AS dias_para_vencimento,
    c.nome_razao_social AS tenant_nome,
    CASE
        WHEN (v.data_venc_tacografo - CURRENT_DATE) <= 7 THEN 'CRITICO_7_DIAS'
        WHEN (v.data_venc_tacografo - CURRENT_DATE) <= 30 THEN 'ALERTA_30_DIAS'
        ELSE 'OK'
    END AS status_alerta
FROM veiculos v
INNER JOIN clientes c ON v.tenant_id = c.id
WHERE v.tacografo_obrigatorio = TRUE
  AND v.data_venc_tacografo IS NOT NULL
  AND v.data_venc_tacografo > CURRENT_DATE
  AND (v.data_venc_tacografo - CURRENT_DATE) <= 30;

