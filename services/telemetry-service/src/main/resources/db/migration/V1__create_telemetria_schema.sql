-- =============================================================================
-- SEÇÃO 10 — USUÁRIOS
-- =============================================================================

CREATE TABLE IF NOT EXISTS usuarios (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login                   VARCHAR(100) NOT NULL UNIQUE,
    senha                   VARCHAR(255) NOT NULL,
    nome                    VARCHAR(255) NOT NULL,
    email                   VARCHAR(200) UNIQUE,
    cpf                     VARCHAR(14) NOT NULL UNIQUE,
    ativo                   BOOLEAN NOT NULL DEFAULT TRUE,
    perfil                  VARCHAR(20) NOT NULL,
    ultimo_acesso           TIMESTAMP,
    motorista_id            BIGINT  UNIQUE,
    -- RN-USR-001: Política de Senha
    data_expiracao_senha    DATE,
    tentativas_falha        INT DEFAULT 0,
    ultima_tentativa_falha  TIMESTAMP,
    bloqueado_ate           TIMESTAMP,
    -- RN-USR-002: MFA
    mfa_secret              VARCHAR(32),
    mfa_ativado             BOOLEAN DEFAULT FALSE,
    criado_em               TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_usr_login ON usuarios (login);
CREATE INDEX IF NOT EXISTS idx_usr_cpf ON usuarios (cpf);
CREATE INDEX IF NOT EXISTS idx_usr_email ON usuarios (email);
CREATE INDEX IF NOT EXISTS idx_usr_bloqueado_ate ON usuarios (bloqueado_ate);
CREATE INDEX IF NOT EXISTS idx_usr_data_expiracao_senha ON usuarios (data_expiracao_senha);

-- =============================================================================
-- SEÇÃO 11 — HISTÓRICO DE SENHAS
-- =============================================================================

CREATE TABLE IF NOT EXISTS historico_senhas (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT  NOT NULL,
    senha_hash  VARCHAR(255) NOT NULL,
    criado_em   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_hs_usuario ON historico_senhas (usuario_id);
CREATE INDEX IF NOT EXISTS idx_hs_criado_em ON historico_senhas (criado_em);

-- =============================================================================
-- SEÇÃO 12 — SESSÕES ATIVAS
-- =============================================================================

CREATE TABLE IF NOT EXISTS sessoes_ativas (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id      BIGINT  NOT NULL,
    token_jwt       VARCHAR(500) NOT NULL,
    ip              VARCHAR(45),
    user_agent      TEXT,
    data_criacao    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ultimo_acesso   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_expiracao  TIMESTAMP NOT NULL,
    FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
);
