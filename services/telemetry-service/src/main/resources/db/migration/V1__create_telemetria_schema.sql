SELECT
    a.*,
    vc.placa,
    mc.nome AS motorista_nome
FROM alertas a
LEFT JOIN veiculos_cache   vc ON a.veiculo_id   = vc.id
LEFT JOIN motoristas_cache mc ON a.motorista_id = mc.id
WHERE a.lido = FALSE
