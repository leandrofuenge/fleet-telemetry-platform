-- SEÇÃO 1 — CADASTROS BASE (caches locais)
-- =============================================================================

CREATE TABLE IF NOT EXISTS veiculos_cache (
    id                  BIGINT  NOT NULL PRIMARY KEY,
    uuid                VARCHAR(36) NOT NULL UNIQUE,
    tenant_id           BIGINT  NOT NULL,
    placa               VARCHAR(10) NOT NULL,
    modelo              VARCHAR(255) NOT NULL,
    marca               VARCHAR(100),
    tipo_veiculo        VARCHAR(50) NOT NULL DEFAULT 'CAMINHAO_PESADO',
    consumo_medio       DOUBLE PRECISION,
    capacidade_carga_kg DOUBLE PRECISION,
    device_id           VARCHAR(64),
    device_imei         VARCHAR(20),
    pbt_kg              DOUBLE PRECISION,
    ativo               BOOLEAN NOT NULL DEFAULT TRUE,
    sincronizado_em     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_vc_tenant ON veiculos_cache (tenant_id);
CREATE INDEX IF NOT EXISTS idx_vc_device ON veiculos_cache (device_id);
CREATE INDEX IF NOT EXISTS idx_vc_placa ON veiculos_cache (placa);

CREATE TABLE IF NOT EXISTS motoristas_cache (
    id              BIGINT  NOT NULL PRIMARY KEY,
    uuid            VARCHAR(36) NOT NULL UNIQUE,
    tenant_id       BIGINT  NOT NULL,
    nome            VARCHAR(255) NOT NULL,
    cpf             VARCHAR(14) NOT NULL,
    cnh             VARCHAR(50) NOT NULL,
    categoria_cnh   VARCHAR(10) NOT NULL,
    ativo           BOOLEAN NOT NULL DEFAULT TRUE,
    sincronizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_mc_tenant ON motoristas_cache (tenant_id);
CREATE INDEX IF NOT EXISTS idx_mc_cpf ON motoristas_cache (cpf);

-- =============================================================================
-- SEÇÃO 1.5 — CLIENTES E CARGAS
-- =============================================================================

CREATE TABLE IF NOT EXISTS clientes (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_razao_social   VARCHAR(255) NOT NULL,
    cnpj                VARCHAR(18) NOT NULL UNIQUE,
    email               VARCHAR(200),
    telefone            VARCHAR(20),
    endereco            VARCHAR(500),
    ativo               BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_cli_cnpj ON clientes (cnpj);

CREATE TABLE IF NOT EXISTS cargas (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao           VARCHAR(500) NOT NULL,
    peso_kg             DOUBLE PRECISION,
    tipo                VARCHAR(50),
    volume_m3           DOUBLE PRECISION,
    nfe_chave           VARCHAR(50),
    cte_chave           VARCHAR(50),
    cliente_id          BIGINT ,
    criado_em           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_car_cliente ON cargas (cliente_id);
CREATE INDEX IF NOT EXISTS idx_car_tipo ON cargas (tipo);

-- =============================================================================
-- SEÇÃO 8 — MOTORISTAS E VEÍCULOS (entidades principais)
-- =============================================================================

CREATE TABLE IF NOT EXISTS motoristas (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           BIGINT  NOT NULL,
    nome                VARCHAR(255) NOT NULL,
    cpf                 VARCHAR(14) NOT NULL,
    cnh                 VARCHAR(20) NOT NULL,
    categoria_cnh       VARCHAR(5) NOT NULL,
    data_venc_cnh       DATE,
    data_venc_aso       DATE,
    mopp_valido         BOOLEAN DEFAULT FALSE,
    score               INT NOT NULL DEFAULT 1000,
    email               VARCHAR(200) UNIQUE,
    telefone            VARCHAR(20),
    ativo               BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- Constraints
    CONSTRAINT uk_motorista_cpf_tenant UNIQUE (cpf, tenant_id),
    CONSTRAINT uk_motorista_cnh UNIQUE (cnh)
);
CREATE INDEX IF NOT EXISTS idx_mot_cpf ON motoristas (cpf);
CREATE INDEX IF NOT EXISTS idx_mot_cnh ON motoristas (cnh);
CREATE INDEX IF NOT EXISTS idx_mot_tenant ON motoristas (tenant_id);
CREATE INDEX IF NOT EXISTS idx_mot_ativo ON motoristas (ativo);
CREATE INDEX IF NOT EXISTS idx_mot_score ON motoristas (score);
CREATE INDEX IF NOT EXISTS idx_mot_venc_cnh ON motoristas (data_venc_cnh);
CREATE INDEX IF NOT EXISTS idx_mot_venc_aso ON motoristas (data_venc_aso);

CREATE TABLE IF NOT EXISTS veiculos (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id               BIGINT  NOT NULL,
    placa                   VARCHAR(10) NOT NULL,
    modelo                  VARCHAR(255),
    marca                   VARCHAR(100),
    capacidade_carga        DOUBLE PRECISION,
    ano_fabricacao          INT,
    ativo                   BOOLEAN NOT NULL DEFAULT TRUE,
    cliente_id              BIGINT ,
    motorista_atual_id      BIGINT ,
    -- RN-VEI-002: Tacógrafo
    pbt_kg                  DOUBLE PRECISION,
    tacografo_obrigatorio   BOOLEAN DEFAULT FALSE,
    data_venc_tacografo     DATE,
    -- RN-VEI-003: Documentos com Vencimento
    data_venc_crlv          DATE,
    data_venc_seguro        DATE,
    data_venc_dpvat         DATE,
    data_venc_rcf           DATE,
    data_venc_vistoria      DATE,
    data_venc_rntrc         DATE,
    criado_em               TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- Constraints
    CONSTRAINT uk_veiculo_placa_tenant UNIQUE (placa, tenant_id)
);
CREATE INDEX IF NOT EXISTS idx_vei_placa ON veiculos (placa);
CREATE INDEX IF NOT EXISTS idx_vei_tenant ON veiculos (tenant_id);
CREATE INDEX IF NOT EXISTS idx_vei_ativo ON veiculos (ativo);
CREATE INDEX IF NOT EXISTS idx_vei_tacografo_venc ON veiculos (data_venc_tacografo);
CREATE INDEX IF NOT EXISTS idx_vei_crlv_venc ON veiculos (data_venc_crlv);
CREATE INDEX IF NOT EXISTS idx_vei_seguro_venc ON veiculos (data_venc_seguro);

-- =============================================================================
-- SEÇÃO 6 — ROTAS
-- =============================================================================

CREATE TABLE IF NOT EXISTS rotas (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                    VARCHAR(255) NOT NULL,
    origem                  VARCHAR(255),
    latitude_origem         DOUBLE PRECISION,
    longitude_origem        DOUBLE PRECISION,
    destino                 VARCHAR(255),
    latitude_destino        DOUBLE PRECISION,
    longitude_destino       DOUBLE PRECISION,
    distancia_prevista      DOUBLE PRECISION,
    tempo_previsto          INT,
    tolerancia_desvio_m     DOUBLE PRECISION DEFAULT 100.0,
    threshold_alerta_m      DOUBLE PRECISION DEFAULT 50.0,
    status                  VARCHAR(30) NOT NULL DEFAULT 'PLANEJADA',
    ativa                   BOOLEAN NOT NULL DEFAULT TRUE,
    data_inicio             TIMESTAMP,
    data_fim                TIMESTAMP,
    pontos_rota             JSON,
    veiculo_id              BIGINT ,
    motorista_id            BIGINT ,
    created_at              TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_rot_veiculo ON rotas (veiculo_id);
CREATE INDEX IF NOT EXISTS idx_rot_motorista ON rotas (motorista_id);
CREATE INDEX IF NOT EXISTS idx_rot_status ON rotas (status);
CREATE INDEX IF NOT EXISTS idx_rot_ativa ON rotas (ativa);

-- =============================================================================
-- SEÇÃO 7 — VIAGENS
-- =============================================================================

CREATE TABLE IF NOT EXISTS viagens (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status                  VARCHAR(20) NOT NULL DEFAULT 'PLANEJADA',
    observacoes             TEXT,
    data_saida              TIMESTAMP,
    data_chegada_prevista   TIMESTAMP,
    data_chegada_real       TIMESTAMP,
    data_inicio             TIMESTAMP,
    distancia_real_km       DOUBLE PRECISION DEFAULT 0.0,
    km_fora_rota            DOUBLE PRECISION DEFAULT 0.0,
    score_viagem            INT DEFAULT 1000,
    veiculo_id              BIGINT ,
    motorista_id            BIGINT ,
    carga_id                BIGINT ,
    rota_id                 BIGINT ,
    created_at              TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_via_veiculo ON viagens (veiculo_id);
CREATE INDEX IF NOT EXISTS idx_via_motorista ON viagens (motorista_id);
CREATE INDEX IF NOT EXISTS idx_via_rota ON viagens (rota_id);
CREATE INDEX IF NOT EXISTS idx_via_status ON viagens (status);
CREATE INDEX IF NOT EXISTS idx_via_saida ON viagens (data_saida);

-- =============================================================================
-- SEÇÃO 2 — TELEMETRIA PRINCIPAL
-- =============================================================================

CREATE TABLE IF NOT EXISTS telemetria (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    -- Identificação
    tenant_id                   BIGINT  NOT NULL,
    veiculo_id                  BIGINT  NOT NULL,
    veiculo_uuid                VARCHAR(36) NOT NULL,
    motorista_id                BIGINT ,
    viagem_id                   BIGINT ,
    device_id                   VARCHAR(64),
    imei_dispositivo            VARCHAR(20),

    -- LOCALIZAÇÃO GPS
    latitude                    DOUBLE PRECISION NOT NULL,
    longitude                   DOUBLE PRECISION NOT NULL,
    altitude                    DOUBLE PRECISION,
    velocidade                  DOUBLE PRECISION NOT NULL DEFAULT 0,
    direcao                     DOUBLE PRECISION,
    hdop                        DOUBLE PRECISION,
    satelites                   INT,
    precisao_gps                DOUBLE PRECISION,
    lat_snap                    DOUBLE PRECISION,
    lng_snap                    DOUBLE PRECISION,
    nome_via                    VARCHAR(255),

    -- MOTOR E DESEMPENHO
    ignicao                     BOOLEAN NOT NULL DEFAULT FALSE,
    rpm                         DOUBLE PRECISION NOT NULL DEFAULT 0,
    carga_motor                 DOUBLE PRECISION,
    torque_motor                DOUBLE PRECISION,
    temperatura_motor           DOUBLE PRECISION,
    pressao_oleo                DOUBLE PRECISION,
    tensao_bateria              DOUBLE PRECISION,
    odometro                    DOUBLE PRECISION NOT NULL DEFAULT 0,
    horas_motor                 DOUBLE PRECISION,
    aceleracao                  DOUBLE PRECISION,
    inclinacao                  DOUBLE PRECISION,

    -- COMBUSTÍVEL
    nivel_combustivel           DOUBLE PRECISION,
    consumo_combustivel         DOUBLE PRECISION,
    consumo_acumulado           DOUBLE PRECISION,
    tempo_ocioso                INT,
    tempo_motor_ligado          INT,

    -- COMPORTAMENTO DO MOTORISTA
    frenagem_brusca             BOOLEAN NOT NULL DEFAULT FALSE,
    numero_frenagens            INT NOT NULL DEFAULT 0,
    numero_aceleracoes_bruscas  INT NOT NULL DEFAULT 0,
    excesso_velocidade          BOOLEAN NOT NULL DEFAULT FALSE,
    velocidade_limite_via       DOUBLE PRECISION,
    curva_brusca                BOOLEAN NOT NULL DEFAULT FALSE,
    pontuacao_motorista         INT,

    -- EVENTOS DE SEGURANÇA
    colisao_detectada           BOOLEAN NOT NULL DEFAULT FALSE,
    geofence_violada            BOOLEAN NOT NULL DEFAULT FALSE,
    geofence_id                 BIGINT ,
    cinto_seguranca             BOOLEAN NOT NULL DEFAULT TRUE,
    porta_aberta                BOOLEAN NOT NULL DEFAULT FALSE,
    botao_panico                BOOLEAN NOT NULL DEFAULT FALSE,
    adulteracao_gps             BOOLEAN NOT NULL DEFAULT FALSE,
    impreciso                   BOOLEAN NOT NULL DEFAULT FALSE,
    preservar_dados             BOOLEAN NOT NULL DEFAULT FALSE,

    -- CARGA
    temperatura_carga           DOUBLE PRECISION,
    umidade_carga               DOUBLE PRECISION,
    peso_carga_kg               DOUBLE PRECISION,
    porta_bau_aberta            BOOLEAN NOT NULL DEFAULT FALSE,
    impacto_carga               BOOLEAN NOT NULL DEFAULT FALSE,
    g_force_impacto             DOUBLE PRECISION,

    -- PNEUS TPMS
    pressao_pneus_json          JSON,
    alerta_pneu                 BOOLEAN NOT NULL DEFAULT FALSE,

    -- CÂMERA DMS
    fadiga_detectada            BOOLEAN NOT NULL DEFAULT FALSE,
    distracao_detectada         BOOLEAN NOT NULL DEFAULT FALSE,
    uso_celular_detectado       BOOLEAN NOT NULL DEFAULT FALSE,
    cigarro_detectado           BOOLEAN NOT NULL DEFAULT FALSE,
    ausencia_cinto_dms          BOOLEAN NOT NULL DEFAULT FALSE,
    score_dms                   INT,

    -- AMBIENTE
    temperatura_externa         DOUBLE PRECISION,
    umidade_externa             DOUBLE PRECISION,
    chuva_detectada             BOOLEAN NOT NULL DEFAULT FALSE,
    condicao_pista              VARCHAR(30),

    -- CONECTIVIDADE
    sinal_gsm                   DOUBLE PRECISION,
    sinal_gps                   DOUBLE PRECISION,
    tecnologia_rede             VARCHAR(10),
    firmware_versao             VARCHAR(30),
    modo_offline                BOOLEAN NOT NULL DEFAULT FALSE,
    delay_sincronizacao_s       INT,

    -- TACÓGRAFO
    tacografo_status            VARCHAR(20),
    tacografo_velocidade        DOUBLE PRECISION,
    tacografo_distancia         DOUBLE PRECISION,
    horas_direcao_acumuladas    DOUBLE PRECISION,

    -- DESGASTE / MANUTENÇÃO
    manutencao_pendente         BOOLEAN NOT NULL DEFAULT FALSE,
    proxima_revisao             TIMESTAMP,
    desgaste_freio              DOUBLE PRECISION,
    dtc_codes                   JSON,

    -- PAYLOAD EXTENSÍVEL
    payload                     JSON,

    -- TIMESTAMPS
    data_hora                   TIMESTAMP NOT NULL,
    recebido_em                 TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processado_em               TIMESTAMP,

    PRIMARY KEY (id, data_hora)
);
CREATE INDEX IF NOT EXISTS idx_tel_veiculo_data ON telemetria (veiculo_id, data_hora DESC);
CREATE INDEX IF NOT EXISTS idx_tel_tenant_data ON telemetria (tenant_id, data_hora DESC);
CREATE INDEX IF NOT EXISTS idx_tel_viagem ON telemetria (viagem_id);
CREATE INDEX IF NOT EXISTS idx_tel_device ON telemetria (device_id);
CREATE INDEX IF NOT EXISTS idx_tel_data_hora ON telemetria (data_hora);
CREATE INDEX IF NOT EXISTS idx_tel_eventos ON telemetria (colisao_detectada, botao_panico, adulteracao_gps);
CREATE INDEX IF NOT EXISTS idx_tel_alertas ON telemetria (excesso_velocidade, frenagem_brusca, geofence_violada);
CREATE INDEX IF NOT EXISTS idx_tel_localizacao ON telemetria (latitude, longitude);
CREATE INDEX IF NOT EXISTS idx_tel_dms ON telemetria (fadiga_detectada, uso_celular_detectado);

