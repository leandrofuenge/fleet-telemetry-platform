-- SEÇÃO 3 — ALERTAS E GEOFENCES
-- =============================================================================

CREATE TABLE IF NOT EXISTS geofences (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid             VARCHAR(36) NOT NULL UNIQUE DEFAULT (gen_random_uuid()::text),
    tenant_id        BIGINT  NOT NULL,
    nome             VARCHAR(255) NOT NULL,
    tipo             VARCHAR(50) NOT NULL DEFAULT 'CIRCULO',
    latitude_centro  DOUBLE PRECISION,
    longitude_centro DOUBLE PRECISION,
    raio             DOUBLE PRECISION,
    vertices         JSON,
    tipo_alerta      VARCHAR(50) NOT NULL DEFAULT 'AMBOS',
    aplica_todos     BOOLEAN NOT NULL DEFAULT TRUE,
    veiculos_uuid    JSON,
    ativo            BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_gf_tenant ON geofences (tenant_id);
CREATE INDEX IF NOT EXISTS idx_gf_ativo ON geofences (ativo);

CREATE TABLE IF NOT EXISTS veiculo_geofence (
    veiculo_id  BIGINT  NOT NULL,
    geofence_id BIGINT  NOT NULL,
    ativo       BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (veiculo_id, geofence_id)
);

CREATE TABLE IF NOT EXISTS alertas (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                    VARCHAR(36) NOT NULL UNIQUE DEFAULT (gen_random_uuid()::text),
    tenant_id               BIGINT  NOT NULL,
    veiculo_id              BIGINT ,
    veiculo_uuid            VARCHAR(36),
    motorista_id            BIGINT ,
    viagem_id               BIGINT ,
    telemetria_id           BIGINT,
    regra_id                BIGINT,
    tipo                    VARCHAR(80) NOT NULL,
    severidade              VARCHAR(50) NOT NULL DEFAULT 'MEDIO',
    categoria               VARCHAR(50),
    mensagem                TEXT NOT NULL,
    latitude                DOUBLE PRECISION,
    longitude               DOUBLE PRECISION,
    velocidade_kmh          DOUBLE PRECISION,
    odometro_km             DOUBLE PRECISION,
    nome_local              VARCHAR(255),
    dados_contexto          JSON,
    data_hora               TIMESTAMP NOT NULL,
    lido                    BOOLEAN NOT NULL DEFAULT FALSE,
    lido_por                VARCHAR(255),
    data_hora_leitura       TIMESTAMP,
    resolvido               BOOLEAN NOT NULL DEFAULT FALSE,
    resolvido_por           VARCHAR(255),
    data_hora_resolucao     TIMESTAMP,
    observacao_resolucao    TEXT,
    notificacao_enviada     BOOLEAN NOT NULL DEFAULT FALSE,
    canais_notificados      JSON,
    criado_em               TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_alerta_tenant ON alertas (tenant_id);
CREATE INDEX IF NOT EXISTS idx_alerta_veiculo ON alertas (veiculo_id);
CREATE INDEX IF NOT EXISTS idx_alerta_motorista ON alertas (motorista_id);
CREATE INDEX IF NOT EXISTS idx_alerta_viagem ON alertas (viagem_id);
CREATE INDEX IF NOT EXISTS idx_alerta_tipo ON alertas (tipo);
CREATE INDEX IF NOT EXISTS idx_alerta_severidade ON alertas (severidade);
CREATE INDEX IF NOT EXISTS idx_alerta_data ON alertas (data_hora);
CREATE INDEX IF NOT EXISTS idx_alerta_lido ON alertas (lido);
CREATE INDEX IF NOT EXISTS idx_alerta_resolvido ON alertas (resolvido);

