-- =============================================================================
-- SEÇÃO 5 — CACHE OSRM E GEOCODING
-- =============================================================================

-- ---------------------------------------------------------------------------
-- TABELA: osrm_route_cache
-- Cache de rotas calculadas para evitar chamadas repetidas ao OSRM.
-- Key = MD5(origem_lat:origem_lng:destino_lat:destino_lng:perfil)
-- TTL recomendado: 7 dias (rotas mudam com obras/updates do mapa)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS osrm_route_cache (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cache_key       VARCHAR(64) NOT NULL UNIQUE,
    perfil          VARCHAR(50) NOT NULL DEFAULT 'CAMINHAO',

    -- Origem e destino (para debug e recalcular se necessário)
    lat_origem      DOUBLE PRECISION NOT NULL,
    lng_origem      DOUBLE PRECISION NOT NULL,
    lat_destino     DOUBLE PRECISION NOT NULL,
    lng_destino     DOUBLE PRECISION NOT NULL,

    -- Resultado OSRM
    distancia_km    DOUBLE PRECISION NOT NULL,
    duracao_min     INT NOT NULL,
    polyline        TEXT,
    geojson         JSON,
    instrucoes      JSON,

    -- Metadados
    hits            INT NOT NULL DEFAULT 1,
    criado_em       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expira_em       TIMESTAMP NOT NULL

);
CREATE INDEX IF NOT EXISTS idx_osrm_key ON osrm_route_cache (cache_key);
CREATE INDEX IF NOT EXISTS idx_osrm_expira ON osrm_route_cache (expira_em);

