    janela_fim          TIMESTAMP,

    -- Execução real
    eta_calculado       TIMESTAMP,
    chegada_real        TIMESTAMP,
    saida_real          TIMESTAMP,
    dentro_janela       BOOLEAN,

    -- Proof of Delivery
