    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id         BIGINT  NOT NULL,
    veiculo_uuid      CHAR(36) NOT NULL,
    nome              VARCHAR(100) NOT NULL,
