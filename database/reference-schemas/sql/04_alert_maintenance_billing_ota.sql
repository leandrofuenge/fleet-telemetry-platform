    horas_instalado   DOUBLE PRECISION,
    vida_util_km_est  DOUBLE PRECISION NOT NULL DEFAULT 100000,
    -- RUL calculado pelo ML
    rul_km_estimado   DOUBLE PRECISION,
    rul_dias_estimado INT,
    anomaly_score     DOUBLE PRECISION NOT NULL DEFAULT 0,
    status            VARCHAR(50) NOT NULL DEFAULT 'BOM',
    ultimo_modelo_ml  VARCHAR(30),
    ultima_pred_em    TIMESTAMP,
    instalado_em      DATE,
    substituido_em    DATE,
    criado_em         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_comp_veiculo ON componentes (veiculo_uuid);
CREATE INDEX IF NOT EXISTS idx_comp_status ON componentes (status);
CREATE INDEX IF NOT EXISTS idx_comp_rul ON componentes (rul_dias_estimado);

-- ---------------------------------------------------------------------------
-- TABELA: predicoes_ml
-- Histórico de predições de manutenção preditiva geradas pelos modelos IA
