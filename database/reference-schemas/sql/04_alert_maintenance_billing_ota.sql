-- =============================================================================
-- ALERT SERVICE — alert_db
-- Responsável: Motor de regras, alertas em tempo real, notificações
-- Porta: 8086
-- =============================================================================

CREATE SCHEMA IF NOT EXISTS alert_db;
SET search_path TO alert_db, public;
-- ---------------------------------------------------------------------------
-- TABELA: regras_alerta
-- Motor de regras configurável por tenant (no-code para gestores)
-- ---------------------------------------------------------------------------
CREATE TABLE regras_alerta (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid             CHAR(36) NOT NULL UNIQUE DEFAULT (gen_random_uuid()::text),
    tenant_id        BIGINT  NOT NULL,
    nome             VARCHAR(255) NOT NULL,
    descricao        TEXT,
    -- Trigger
    tipo_evento      VARCHAR(50) NOT NULL,
    condicoes        JSON NOT NULL,
    logica           VARCHAR(50) NOT NULL DEFAULT 'AND',
    duracao_seg      INT NOT NULL DEFAULT 0,
    -- Ação
    severidade       VARCHAR(50) NOT NULL DEFAULT 'MEDIO',
    acoes            JSON NOT NULL,
    cooldown_min     INT NOT NULL DEFAULT 15,
    -- Escopo
    aplica_todos     BOOLEAN NOT NULL DEFAULT TRUE,
    veiculos_uuid    JSON,
    tipo_carga       JSON,
    -- Controle
    ativo            BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_regra_tenant ON regras_alerta (tenant_id);
CREATE INDEX IF NOT EXISTS idx_regra_ativo ON regras_alerta (ativo);
CREATE INDEX IF NOT EXISTS idx_regra_tipo ON regras_alerta (tipo_evento);

-- ---------------------------------------------------------------------------
-- TABELA: alertas
-- Alertas gerados — cada disparo do motor de regras cria um registro
-- ---------------------------------------------------------------------------
CREATE TABLE alertas (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid             CHAR(36) NOT NULL UNIQUE DEFAULT (gen_random_uuid()::text),
    tenant_id        BIGINT  NOT NULL,
    regra_id         BIGINT ,
    veiculo_uuid     CHAR(36) NOT NULL,
    motorista_uuid   CHAR(36),
    viagem_uuid      CHAR(36),

    tipo             VARCHAR(80) NOT NULL,
    severidade       VARCHAR(50) NOT NULL DEFAULT 'MEDIO',
    mensagem         TEXT NOT NULL,
    dados_contexto   JSON,

    -- Localização no momento do alerta
    latitude         DOUBLE PRECISION,
    longitude        DOUBLE PRECISION,
    velocidade_kmh   DOUBLE PRECISION,
    odometro_km      DOUBLE PRECISION,

    data_hora        TIMESTAMP NOT NULL,

    -- Gestão
    lido             BOOLEAN NOT NULL DEFAULT FALSE,
    lido_por         VARCHAR(255),
    data_hora_leitura TIMESTAMP,
    resolvido        BOOLEAN NOT NULL DEFAULT FALSE,
    resolvido_por    VARCHAR(255),
    data_hora_resolucao TIMESTAMP,
    observacao_resolucao TEXT,

    criado_em        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

 CONSTRAINT fk_alerta_regra FOREIGN KEY (regra_id) REFERENCES regras_alerta(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_alerta_tenant ON alertas (tenant_id);
CREATE INDEX IF NOT EXISTS idx_alerta_veiculo ON alertas (veiculo_uuid);
CREATE INDEX IF NOT EXISTS idx_alerta_tipo ON alertas (tipo);
CREATE INDEX IF NOT EXISTS idx_alerta_sev ON alertas (severidade);
CREATE INDEX IF NOT EXISTS idx_alerta_data ON alertas (data_hora);
CREATE INDEX IF NOT EXISTS idx_alerta_lido ON alertas (lido);
CREATE INDEX IF NOT EXISTS idx_alerta_resolv ON alertas (resolvido);

-- ---------------------------------------------------------------------------
-- TABELA: notificacoes
-- Fila de notificações enviadas para cada canal
-- ---------------------------------------------------------------------------
CREATE TABLE notificacoes (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT  NOT NULL,
    alerta_id        BIGINT ,
    canal            VARCHAR(50) NOT NULL,
    destinatario     VARCHAR(255) NOT NULL,
    assunto          VARCHAR(255),
    corpo            TEXT NOT NULL,
    status           VARCHAR(50) NOT NULL DEFAULT 'PENDENTE',
    tentativas       SMALLINT  NOT NULL DEFAULT 0,
    proximo_retry    TIMESTAMP,
    id_externo       VARCHAR(100),
    erro_detalhe     TEXT,
    enviado_em       TIMESTAMP,
    criado_em        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_notif_alerta FOREIGN KEY (alerta_id) REFERENCES alertas(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_notif_tenant ON notificacoes (tenant_id);
CREATE INDEX IF NOT EXISTS idx_notif_alerta ON notificacoes (alerta_id);
CREATE INDEX IF NOT EXISTS idx_notif_status ON notificacoes (status);
CREATE INDEX IF NOT EXISTS idx_notif_retry ON notificacoes (proximo_retry, status);

-- ---------------------------------------------------------------------------
-- TABELA: webhook_deliveries
-- Histórico de entregas de webhooks para integrações externas
-- ---------------------------------------------------------------------------
CREATE TABLE webhook_deliveries (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       BIGINT  NOT NULL,
    alerta_uuid     CHAR(36),
    url_destino     VARCHAR(500) NOT NULL,
    payload         JSON NOT NULL,
    http_status     SMALLINT,
    resposta        TEXT,
    tentativa       SMALLINT  NOT NULL DEFAULT 1,
    sucesso         BOOLEAN NOT NULL DEFAULT FALSE,
    enviado_em      TIMESTAMP NOT NULL,
    criado_em       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_whd_tenant ON webhook_deliveries (tenant_id);
CREATE INDEX IF NOT EXISTS idx_whd_sucesso ON webhook_deliveries (sucesso);
CREATE INDEX IF NOT EXISTS idx_whd_enviado ON webhook_deliveries (enviado_em);


