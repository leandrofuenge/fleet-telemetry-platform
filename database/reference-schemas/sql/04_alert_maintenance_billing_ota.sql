    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid              CHAR(36) NOT NULL UNIQUE DEFAULT (gen_random_uuid()::text),
    tenant_id         BIGINT  NOT NULL,
    firmware_id       BIGINT  NOT NULL,
    estrategia        VARCHAR(50) NOT NULL DEFAULT 'CANARY_1PCT',
    dispositivos_alvo JSON,
